const DICTS = { km: KM, en: EN };

class I18nManager {
  constructor() {
    this.currentLang = 'km'; // Default language is Khmer
  }

  init() {
    try {
      const saved = localStorage.getItem('dubber_lang');
      if (saved && (saved === 'km' || saved === 'en')) {
        this.currentLang = saved;
      }
    } catch (_) {}

    this.applyToDOM();
  }

  getLanguage() {
    return this.currentLang;
  }

  t(key, params = {}) {
    const dict = DICTS[this.currentLang] || DICTS.km;
    let text = dict[key] || DICTS.km[key] || key;

    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    }
    return text;
  }

  setLanguage(lang) {
    if (lang !== 'km' && lang !== 'en') return;
    this.currentLang = lang;
    try {
      if (typeof localStorage !== 'undefined') localStorage.setItem('dubber_lang', lang);
    } catch (_) {}

    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
      this.applyToDOM();
    }
    state.emit('languageChange', lang);
  }

  toggleLanguage() {
    const nextLang = this.currentLang === 'km' ? 'en' : 'km';
    this.setLanguage(nextLang);
    return nextLang;
  }

  applyToDOM() {
    // Update elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (key) el.textContent = this.t(key);
    });

    // Update titles with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.dataset.i18nTitle;
      if (key) el.title = this.t(key);
    });

    // Update placeholders with data-i18n-ph
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.dataset.i18nPh;
      if (key) el.placeholder = this.t(key);
    });

    // Update aria labels with data-i18n-aria
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.dataset.i18nAria;
      if (key) el.setAttribute('aria-label', this.t(key));
    });

    // Update language switch button text
    const langBtn = document.getElementById('lang');
    if (langBtn) {
      langBtn.textContent = this.currentLang === 'km' ? 'EN' : 'KM';
      langBtn.title = this.currentLang === 'km' ? 'Switch to English' : 'ប្តូរទៅជាភាសាខ្មែរ';
    }
  }
}

export const i18n = new I18nManager();
export const t = (key, params) => i18n.t(key, params);
